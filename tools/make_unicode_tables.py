#!/usr/bin/env python3
"""Writes core/unitab.c: the Unicode facts core/ustr.c needs to treat text
exactly as Python's str does in tools/rb_to_stations.py (isspace, isalnum,
isdigit, the categories clean() removes, lower(), and the accent folding
of fold()). The data comes from this Python's unicodedata; the Unicode
version is written into the file.

    python3 tools/make_unicode_tables.py > core/unitab.c

Standard library only.
"""
import sys
import unicodedata

F_SPACE, F_ALNUM, F_DIGIT, F_CC, F_CFZ, F_CASED, F_IGNORABLE = 1, 2, 4, 8, 16, 32, 64
# Case-ignorable (Unicode's definition, for the final sigma rule): these
# categories, plus the Word_Break MidLetter/MidNumLet/Single_Quote marks.
IGNORABLE_CATS = {"Mn", "Me", "Cf", "Lm", "Sk"}
IGNORABLE_EXTRA = {0x27, 0x2E, 0x3A, 0xB7, 0x387, 0x55F, 0x5F4, 0x2018, 0x2019, 0x2024,
                   0x2027, 0xFE13, 0xFE52, 0xFE55, 0xFF07, 0xFF0E, 0xFF1A}
HANGUL_FIRST, HANGUL_LAST = 0xAC00, 0xD7A3  # decomposed in code, not tabled


def flags(cp):
    ch = chr(cp)
    cat = unicodedata.category(ch)
    f = 0
    if ch.isspace():
        f |= F_SPACE
    if ch.isalnum():
        f |= F_ALNUM
    if ch.isdigit():
        f |= F_DIGIT
    if cat == "Cc":
        f |= F_CC
    if cat in ("Cf", "Zl", "Zp"):
        f |= F_CFZ
    if ch.islower() or ch.isupper() or ch.istitle():
        f |= F_CASED
    if cat in IGNORABLE_CATS or cp in IGNORABLE_EXTRA:
        f |= F_IGNORABLE
    return f


def decomp(ch):
    """NFKD without combining marks: what fold() keeps of one character."""
    return "".join(c for c in unicodedata.normalize("NFKD", ch) if not unicodedata.combining(c))


def main():
    out = sys.stdout
    ranges = []
    prev = None
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            f = 0
        else:
            f = flags(cp)
        if prev is not None and prev[2] == f and prev[1] == cp - 1:
            prev[1] = cp
        else:
            if prev is not None and prev[2]:
                ranges.append(tuple(prev))
            prev = [cp, cp, f]
    if prev[2]:
        ranges.append(tuple(prev))

    pool = []
    lower, fold = [], []
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        ch = chr(cp)
        lo = ch.lower()
        if lo != ch:
            lower.append((cp, len(pool), len(lo)))
            pool.extend(ord(c) for c in lo)
        if not (HANGUL_FIRST <= cp <= HANGUL_LAST):
            d = decomp(ch)
            if d != ch:
                fold.append((cp, len(pool), len(d)))
                pool.extend(ord(c) for c in d)

    w = out.write
    w("/* Generated by tools/make_unicode_tables.py from Python %s's unicodedata\n"
      " * (Unicode %s). Do not edit. */\n" % (sys.version.split()[0], unicodedata.unidata_version))
    w('#include "ustr.h"\n\n')
    w("const char UNITAB_VERSION[] = \"%s\";\n\n" % unicodedata.unidata_version)
    w("const unitab_range UNITAB_FLAGS[] = {\n")
    for a, b, f in ranges:
        w("    { 0x%X, 0x%X, %d },\n" % (a, b, f))
    w("};\nconst size_t UNITAB_FLAGS_N = %d;\n\n" % len(ranges))
    w("const uint32_t UNITAB_POOL[] = {\n")
    for i in range(0, len(pool), 12):
        w("    " + ", ".join("0x%X" % c for c in pool[i:i + 12]) + ",\n")
    w("};\n\n")
    for name, tab in (("LOWER", lower), ("FOLD", fold)):
        w("const unitab_map UNITAB_%s[] = {\n" % name)
        for cp, off, n in tab:
            w("    { 0x%X, %d, %d },\n" % (cp, off, n))
        w("};\nconst size_t UNITAB_%s_N = %d;\n\n" % (name, len(tab)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
